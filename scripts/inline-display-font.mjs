#!/usr/bin/env node
/**
 * Writes src/app/fonts/display-font.css: the display face (Dela Gothic One,
 * Latin subset) as a data URI inside its @font-face rule.
 *
 *   node scripts/inline-display-font.mjs
 *
 * Re-run it only when src/app/fonts/dela-gothic-one-latin.woff2 changes; the
 * output is committed.
 *
 * Why inline: the display face sets every page's headline, and the headline
 * is usually the page's Largest Contentful Paint. Loaded as its own file, the
 * font could land a moment after the first paint, and Chrome does not count
 * the headline as painted until the swap. On a phone that read as a ~3 s LCP
 * in Lighthouse while the words were on screen at ~1.3 s. Inside the
 * stylesheet the font exists as soon as the styles do: no swap, no wait, no
 * layout shift. It costs ~15 KB in the render-blocking CSS, once; the
 * stylesheet is cached across every page.
 *
 * Dela Gothic One is SIL Open Font License 1.1 (Google Fonts).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();
const SRC = path.join(ROOT, 'src/app/fonts/dela-gothic-one-latin.woff2');
const OUT = path.join(ROOT, 'src/app/fonts/display-font.css');

const b64 = readFileSync(SRC).toString('base64');

const css = `/* GENERATED by scripts/inline-display-font.mjs — do not edit by hand.
   Dela Gothic One (Latin subset), SIL OFL 1.1, inlined so every headline
   paints in its own face on the first frame. */
@font-face {
  font-family: 'Dela Gothic One';
  font-style: normal;
  font-weight: 400;
  font-display: swap;
  src: url(data:font/woff2;base64,${b64}) format('woff2');
}
:root {
  --font-dela: 'Dela Gothic One';
}
`;

writeFileSync(OUT, css);
console.log(`wrote ${path.relative(ROOT, OUT)} — ${(Buffer.byteLength(css) / 1024).toFixed(1)} KB`);
