#!/usr/bin/env node
/**
 * Writes the Broom & Blade Arcade's loops: src/app/games/guild/loops.css.
 *
 *   node scripts/build-guild-loops.mjs
 *
 * Re-run it only when a loop's shape changes; the output is committed.
 *
 * THE RULE (2026-10-05, measured in Chromium): every infinite CSS loop wakes
 * the main thread at each iteration boundary (React listens for
 * `animationiteration` at its root), and each wake restyles every running
 * animation. So the hall runs FEW, LONG, SHARED loops: one 16 s clock, no
 * per-element delays. Fast motion (a flame's flicker, the marquee's chase)
 * is written as beats inside the 16 s keyframes; torches differ by having
 * their own keyframes (variants a, b, c), not by being offset in time; and a
 * group is animated as one overlay rather than bulb by bulb.
 *
 * The beats are pseudo-random but seeded, so the file is the same on every
 * run. Opacity and transform (scale, rotate, translate) only: the compositor
 * draws all of it. Every loop is gated on its zone's [data-live] (HallFX),
 * paused while the page scrolls (.gh-world[data-hold] .gh-loop, guild.css),
 * and absent under reduced motion.
 */
import { writeFileSync } from 'node:fs';
import path from 'node:path';

const OUT = path.join(process.cwd(), 'src/app/games/guild/loops.css');
const CLOCK = 16; // seconds: the one shared period

// A small seeded generator (mulberry32).
function rng(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const f = (n, d = 3) => {
  const v = Number(n.toFixed(d));
  return Object.is(v, -0) ? '0' : String(v);
};
const pct = (x) => `${f(x * 100, 2)}%`;

/** Beats at roughly even spacing with a little jitter; first and last match. */
function beats(seed, count, make) {
  const r = rng(seed);
  const out = [];
  for (let i = 0; i < count; i++) {
    const at = i === 0 ? 0 : (i + (r() - 0.5) * 0.5) / count;
    out.push([at, make(r, i)]);
  }
  out.push([1, out[0][1]]);
  return out;
}
// One keyframe per line: the file is generated, so it is kept compact.
const kf = (name, frames) =>
  `@keyframes ${name} {\n${frames.map(([at, body]) => `  ${typeof at === 'string' ? at : pct(at)} { ${body.replace(/\n\s*/g, ' ')} }`).join('\n')}\n}\n`;

let css = `/* GENERATED by scripts/build-guild-loops.mjs — do not edit by hand.

   The hall's loops: one shared ${CLOCK} s clock, beats inside it (see the
   script for why). Gated on [data-live], held while scrolling, absent under
   reduced motion. */
`;

// ── Torches ─────────────────────────────────────────────────────────────────
// The three flame layers move as one (.gh-burn): a flicker every ~0.45 s, a
// lean now and then. The halo breathes slower. Two sparks rise together
// (.gh-embers) five or six times a cycle, then hang invisible until the next.
const VARIANTS = { a: 11, b: 23, c: 37 };
for (const [v, seed] of Object.entries(VARIANTS)) {
  css += kf(
    `gh-burn-${v}`,
    beats(seed, 34, (r, i) => {
      if (i === 0) return 'scale: 1 1;\n    rotate: 0deg;';
      const sx = 1 + (r() - 0.5) * 0.14;
      const sy = 1 + (r() - 0.45) * 0.22;
      const rot = (r() - 0.5) * 6;
      return `scale: ${f(sx)} ${f(sy)};\n    rotate: ${f(rot, 2)}deg;`;
    }),
  );
  css += kf(
    `gh-halo-${v}`,
    beats(seed + 1, 14, (r, i) => {
      if (i === 0) return 'opacity: 1;\n    scale: 1;';
      return `opacity: ${f(0.72 + r() * 0.28)};\n    scale: ${f(0.93 + r() * 0.12)};`;
    }),
  );
  // Sparks: each rise takes ~1.6 s of the cycle.
  const r = rng(seed + 2);
  const rises = [];
  let t = r() * 0.08;
  while (t < 0.86) {
    rises.push(t);
    t += 0.13 + r() * 0.07;
  }
  const rise = 1.6 / CLOCK;
  const frames = [[0, 'opacity: 0;\n    translate: 0 0;\n    scale: 1;']];
  for (const s of rises) {
    const dx = f((r() - 0.3) * 14, 1);
    frames.push([s, 'opacity: 0;\n    translate: 0 0;\n    scale: 1;']);
    frames.push([s + rise * 0.15, 'opacity: 1;']);
    frames.push([s + rise, `opacity: 0;\n    translate: calc(var(--u) * ${dx}) calc(var(--u) * -50);\n    scale: 0.4;`]);
    frames.push([s + rise + 0.001, 'opacity: 0;\n    translate: 0 0;\n    scale: 1;']);
  }
  frames.push([1, 'opacity: 0;\n    translate: 0 0;\n    scale: 1;']);
  css += kf(`gh-embers-${v}`, frames);
}

// ── The neon sign: a buzz, twice a cycle ───────────────────────────────────
css += `@keyframes gh-buzz {
  0%, 31%, 31.6%, 71%, 71.6%, 72.4%, 100% { opacity: 1; }
  31.3%, 71.3% { opacity: 0.4; }
  72% { opacity: 0.7; }
}
`;

// ── Bulbs: the awning's and the festoon's twinkle in two groups ────────────
// Four slow breaths a cycle, the second group in the opposite phase.
for (const g of [0, 1]) {
  const frames = [];
  for (let k = 0; k <= 8; k++) frames.push([k / 8, `opacity: ${(k + g) % 2 ? '0.5' : '1'};`]);
  css += kf(`gh-twinkle-${g}`, frames);
}

// ── The signboard's marquee: three groups take turns going dark ─────────────
// Thirty steps a cycle (0.53 s each, ten full rounds), held, not eased.
const STEPS = 30;
for (const g of [0, 1, 2]) {
  const dark = [];
  const lit = [];
  for (let k = 0; k <= STEPS; k++) ((k % 3) === g ? dark : lit).push(`${f((k / STEPS) * 100, 2)}%`);
  css += `@keyframes gh-chase-${g} {\n  ${lit.join(', ')} { opacity: 1; }\n  ${dark.join(', ')} { opacity: 0.14; }\n}\n`;
}

// ── Swing: the sign twice a cycle, the banners once, in opposite phase ─────
const swing = (name, swings, amp) => {
  const frames = [];
  for (let k = 0; k <= swings * 2; k++)
    frames.push([k / (swings * 2), `rotate: ${f(k % 2 ? amp : -amp, 2)}deg;\n    animation-timing-function: ease-in-out;`]);
  return kf(name, frames);
};
css += swing('gh-sway', 2, 0.7);
css += swing('gh-sway-l', 1, 1.1);
css += swing('gh-sway-r', 1, -1.1);

// ── Dust: three layers of motes drift as one each ──────────────────────────
for (const [g, seed] of [[0, 5], [1, 17], [2, 29]]) {
  const r = rng(seed);
  const frames = [];
  for (let k = 0; k <= 6; k++) {
    if (k === 0 || k === 6) frames.push([k / 6, 'translate: 0 0;\n    opacity: 0.55;\n    animation-timing-function: ease-in-out;']);
    else
      frames.push([
        k / 6,
        `translate: ${f((r() - 0.5) * 34, 1)}px ${f(-r() * 30, 1)}px;\n    opacity: ${f(0.25 + r() * 0.75, 2)};\n    animation-timing-function: ease-in-out;`,
      ]);
  }
  css += kf(`gh-drift-${g}`, frames);
}

// ── Who runs what ─────────────────────────────────────────────────────────
css += `
@media (prefers-reduced-motion: no-preference) {
  [data-live] .gh-loop {
    animation-duration: ${CLOCK}s;
    animation-iteration-count: infinite;
    animation-timing-function: linear;
  }
  [data-live] .gh-burn[data-v='a'] { animation-name: gh-burn-a; }
  [data-live] .gh-burn[data-v='b'] { animation-name: gh-burn-b; }
  [data-live] .gh-burn[data-v='c'] { animation-name: gh-burn-c; }
  [data-live] .gh-halo[data-v='a'] { animation-name: gh-halo-a; }
  [data-live] .gh-halo[data-v='b'] { animation-name: gh-halo-b; }
  [data-live] .gh-halo[data-v='c'] { animation-name: gh-halo-c; }
  [data-live] .gh-embers[data-v='a'] { animation-name: gh-embers-a; }
  [data-live] .gh-embers[data-v='b'] { animation-name: gh-embers-b; }
  [data-live] .gh-embers[data-v='c'] { animation-name: gh-embers-c; }
  .gh-stair[data-live] .gh-neon-main { animation-name: gh-buzz; }
  [data-live] .gh-awning-g[data-g='0'],
  [data-live] .gh-festoon-g[data-g='0'] { animation-name: gh-twinkle-0; }
  [data-live] .gh-awning-g[data-g='1'],
  [data-live] .gh-festoon-g[data-g='1'] { animation-name: gh-twinkle-1; }
  [data-live] .gh-bulbs-g[data-g='0'] { animation-name: gh-chase-0; animation-timing-function: steps(1, end); }
  [data-live] .gh-bulbs-g[data-g='1'] { animation-name: gh-chase-1; animation-timing-function: steps(1, end); }
  [data-live] .gh-bulbs-g[data-g='2'] { animation-name: gh-chase-2; animation-timing-function: steps(1, end); }
  [data-live] .gh-sign-swing { animation-name: gh-sway; }
  [data-live] .gh-banner-l { animation-name: gh-sway-l; }
  [data-live] .gh-banner-r { animation-name: gh-sway-r; }
  [data-live] .gh-motes-g[data-g='0'] { animation-name: gh-drift-0; }
  [data-live] .gh-motes-g[data-g='1'] { animation-name: gh-drift-1; }
  [data-live] .gh-motes-g[data-g='2'] { animation-name: gh-drift-2; }
}
`;

writeFileSync(OUT, css);
console.log(`wrote ${path.relative(process.cwd(), OUT)} (${(Buffer.byteLength(css) / 1024).toFixed(1)} KB)`);
